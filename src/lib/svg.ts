/* ============================================================
   ORNAMENTS — hand-drawn details, built as SVG nodes.
   Deliberately imperfect paths (slightly asymmetric curves) so the
   decorations read as drawn by a person, not generated by a script.
   ============================================================ */

const SVG_NS = 'http://www.w3.org/2000/svg';

export interface PathSpec {
  readonly d: string;
  readonly fill?: string;
  readonly stroke?: string;
  readonly strokeWidth?: number;
  readonly fillOpacity?: number;
}

export interface SvgGroupSpec {
  /** Paths that move as one piece — a slice of cake, a lid, a flap. */
  readonly className: string;
  readonly paths: readonly PathSpec[];
}

export interface SvgSpec {
  readonly viewBox: string;
  readonly width: number;
  readonly height: number;
  readonly paths: readonly PathSpec[];
  readonly groups?: readonly SvgGroupSpec[];
  readonly className?: string;
  readonly ariaHidden?: boolean;
  readonly label?: string;
}

function applyPaint(node: SVGPathElement, spec: PathSpec): void {
  node.setAttribute('d', spec.d);
  node.setAttribute('fill', spec.fill ?? 'none');
  if (spec.stroke) {
    node.setAttribute('stroke', spec.stroke);
    node.setAttribute('stroke-width', String(spec.strokeWidth ?? 1.2));
    node.setAttribute('stroke-linecap', 'round');
    node.setAttribute('stroke-linejoin', 'round');
  }
  if (spec.fillOpacity !== undefined) {
    node.setAttribute('fill-opacity', String(spec.fillOpacity));
  }
}

export function svg(spec: SvgSpec): SVGSVGElement {
  const root = document.createElementNS(SVG_NS, 'svg');
  root.setAttribute('viewBox', spec.viewBox);
  root.setAttribute('width', String(spec.width));
  root.setAttribute('height', String(spec.height));
  root.setAttribute('fill', 'none');
  if (spec.className) root.setAttribute('class', spec.className);

  if (spec.ariaHidden === false) {
    root.setAttribute('role', 'img');
    root.setAttribute('aria-label', spec.label ?? '');
  } else {
    root.setAttribute('aria-hidden', 'true');
    root.setAttribute('focusable', 'false');
  }

  for (const path of spec.paths) {
    const node = document.createElementNS(SVG_NS, 'path');
    applyPaint(node, path);
    root.append(node);
  }

  for (const group of spec.groups ?? []) {
    const node = document.createElementNS(SVG_NS, 'g');
    node.setAttribute('class', group.className);
    for (const path of group.paths) {
      const child = document.createElementNS(SVG_NS, 'path');
      applyPaint(child, path);
      node.append(child);
    }
    root.append(node);
  }

  return root;
}

